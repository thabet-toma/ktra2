/**
 * التلميح إن وُجد نصُّه، و`null` خلافه. **مفتاحٌ ناقص لا يكسر شاشة**: لا تظهر
 * أيقونةٌ أصلاً، ولا يظهر تلميحٌ فارغ يوهم المستخدم أن ثمّة شرحاً غائباً.
 * والنصّ الفارغ كالمفقود تماماً — أيقونةٌ تفتح فراغاً أسوأ من لا أيقونة.
 */
export function simpleHintFor(key: string): SimpleHint | null {
  // خاصّية الكائن نفسه لا موروثة: `'toString'` مفتاحٌ موجودٌ على كل كائن، ولولا
  // هذا الشرط لأعاد دالةً ثم انكسر عند قراءة عنوانها.
  if (!Object.prototype.hasOwnProperty.call(SIMPLE_HINTS, key)) return null;
  const hint = (SIMPLE_HINTS as Record<string, SimpleHint | undefined>)[key];
  if (!hint) return null;
  if (!hint.title.trim()) return null;
  if (hint.lines.some((line) => !line.trim())) return null;
  return hint;
}
