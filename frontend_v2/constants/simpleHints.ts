/**
 * THA-110 — نصوص «؟» في الوضع السهل: **ملفٌ واحد قابل للتحرير** كما طلب المالك.
 *
 * كل نصٍّ يظهر في تلميحٍ داخل الواجهة يُكتب هنا ولا يُكتب في أي مكوّن. المكوّن
 * (`components/ui/FieldHint.tsx`) لا يحمل حرفاً عربياً واحداً، فتحرير النصوص
 * لاحقاً لا يمسّ شيفرةً ولا يفتح باب انحدار.
 *
 * **المفاتيح مجمَّدة** — أُغلقت قائمتها في T5 كي تكتب T6 نصوصها على مفاتيح
 * موجودة بلا اختراع مفتاحٍ جديد. مفاتيح القائمة مشتقّة من `SIMPLE_VIEWS` نفسها
 * لا منسوخة عنها: بندٌ يُضاف أو يُحذف هناك **يكسر البناء هنا** بدل أن يمرّ
 * صامتاً بتلميحٍ يتيم أو شاشةٍ بلا شرح.
 *
 * الشكل: عنوانٌ قصير (اسم العنصر كما يراه المستخدم) + **سطران لا ثالث لهما**:
 * ما هذا العنصر · وماذا يحدث إن تركته كما هو. هذا سقفٌ مقصود — التلميح جملةٌ
 * تُقرأ في ثانيتين لا صفحةُ توثيق.
 */
