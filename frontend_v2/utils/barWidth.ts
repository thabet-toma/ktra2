/**
 * عرضُ شريط تقدّمٍ صنفَ Tailwind ثابتاً — لا `style` سطريّاً ولا صنفاً مبنيّاً
 * وقتَ التشغيل.
 *
 * القاعدتان معاً هما سببُ وجود هذا الملفّ:
 *
 * - **`style={{ width }}` يخالف قاعدةَ المستودع** (Tailwind وحدَه، بلا أنماطٍ
 *   سطريّة) ولا يمسكه `tsc` ولا `npm test` — لا أحدَهما يرى JSX مُصيَّراً.
 * - **وصنفٌ مبنيٌّ نصّاً مثل `` `w-[${n}%]` `` لا يراه ماسحُ Tailwind السكونيّ**
 *   فلا يولّد قاعدتَه أصلاً: الشريطُ يبقى بعرض صفرٍ **بلا خطأٍ في أيّ مكان**.
 *   لذلك الخطواتُ مكتوبةٌ حرفيّةً هنا.
 *
 * وكان هذا السُلَّمُ يسكن `TeamTargetBars.tsx` وحدَه (211-S)؛ نُقل إلى أداةٍ
 * مشتركةٍ حين لزم شريطٌ ثانٍ في «خطّتي» — نسخةٌ ثانيةٌ من سُلَّمٍ كهذا تتباعد
 * عن أختها بصمتٍ وتُخرج شريطين بدقّتين مختلفتين في الشاشة نفسها.
 */

// الخطوةُ ٥٪ — أدقُّ ممّا يحتاجه شريطُ ملخّص، ولا تُقرأ العينُ فرقاً أصغر.
export const BAR_WIDTH_STEPS: readonly string[] = [
  'w-0',
  'w-[5%]',
  'w-[10%]',
  'w-[15%]',
  'w-[20%]',
  'w-[25%]',
  'w-[30%]',
  'w-[35%]',
  'w-[40%]',
  'w-[45%]',
  'w-[50%]',
  'w-[55%]',
  'w-[60%]',
  'w-[65%]',
  'w-[70%]',
  'w-[75%]',
  'w-[80%]',
  'w-[85%]',
  'w-[90%]',
  'w-[95%]',
  'w-full',
];

/** صنفُ العرض لنسبةٍ مئويّة — مقصوصةٌ في [0,100]، و`NaN` تُعامَل صفراً. */
export function barWidthClass(percent: number): string {
  if (!Number.isFinite(percent)) return BAR_WIDTH_STEPS[0];
  const clamped = Math.max(0, Math.min(100, percent));
  return BAR_WIDTH_STEPS[Math.round(clamped / 5)];
}
