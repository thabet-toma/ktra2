/**
 * رقم مستند داخل خلية ضيّقة (عمود «رقم المستند» في قوائم العروض والطلبيات).
 *
 * القصّ بـ`text-overflow: ellipsis` وحده يأكل **الذيل**، وذيل رقم المستند هو
 * المميِّز الوحيد بين سجلّين (`IQ-000000006` و`IQ-000000007` يصيران نصّاً
 * واحداً). والقصّ من الصدر يمحو **النوع**: القائمة نفسها تخلط `IQ` (استيراد)
 * و`PQ` (شراء) و`PO` (طلبية شراء)، فصدرُها ليس ثابتاً كما يبدو من سجلّ واحد.
 * فالقصّ من الوسط: تبقى بادئة النوع ويبقى الذيل المميِّز، والكامل في التلميح
 * (`title`) — وهو ما توصي به أدلّة الأنماط حين يميّز الطرفان معاً (PatternFly).
 *
 * والرقم الذي يتّسع لا يُقصّ أصلاً: `IQ-00006` يبقى كما هو.
 */

/** أقصى طول يُعرض كاملاً قبل القصّ — يتّسع له عمود 150px بجانب صورة 36px. */
const DEFAULT_MAX = 12;
/** عدد المحارف المحفوظة من الذيل — المميِّز بين سجلّ وآخر. */
const DEFAULT_TAIL = 6;

/**
 * يعيد الرقم كما هو إن اتّسع، وإلا `بادئة…ذيل`.
 * لا يُستعمل للبحث ولا للمقارنة — للعرض فقط؛ القيمة الكاملة تبقى في `title`.
 */
export function elideDocumentNumber(
  value?: string | null,
  max: number = DEFAULT_MAX,
  keepTail: number = DEFAULT_TAIL,
): string {
  const text = String(value ?? "").trim();
  if (text.length <= max) return text;

  const tail = text.slice(-keepTail);
  // بادئة النوع: ما قبل أول رقم أو فاصل (IQ من IQ-000000123)، وبحدّ أربعة
  // محارف كي لا يبتلع رقمٌ بلا فواصل نصفَ نفسه في الصدر.
  const head = /^[^\d\s\-_/\\]{1,4}/.exec(text)?.[0] ?? text.slice(0, 2);
  const elided = `${head}…${tail}`;
  // القصّ الذي لا يقصّ (رقم قصير بحدود واسعة) يضيف «…» بلا فائدة.
  return elided.length < text.length ? elided : text;
}

/** أطول تسلسل يُعرض وحده — أطول من ذلك لم يعد «رقماً قصيراً» فيُقصّ كالمعتاد. */
const MAX_SERIAL_DIGITS = 6;

/**
 * التسلسل وحده: `IQ-0006` ← `6`.
 *
 * المالك: «الرقم ملوش لزمة كثير، ماكل الصور» — في قائمةٍ صورةُ العرض هي
 * مميِّزها البصري، والبادئة الثابتة (`IQ-` في كل صفّ) والأصفار الحاشية لا
 * تميّز شيئاً بينما تأكل نصف الخانة. فيُعرض الجزء المتغيّر وحده، والكامل يبقى
 * في `title` وفي البحث. هذا نمط مألوف في الأدوات الحديثة (Linear/Shopify يعرضان
 * التسلسل مختصراً `#1001` لا المرجع كاملاً في كل صفّ).
 *
 * الخطر الوحيد أن يتصادم تسلسلان من نوعين (`PQ-0006` و`PO-0006` كلاهما `6`) —
 * وحلُّه عند المستدعي: يقارن التسلسلات المعروضة، وعند التصادم يعرض الأرقام
 * كاملةً بـ`elideDocumentNumber`. هذه الدالّة تصف صفّاً واحداً لا قائمة.
 *
 * وما ليس «بادئة + أصفار + تسلسل قصير» (تاريخ مضغوط، أو رقم عربي، أو تسلسل
 * أطول من ستّ خانات) يُعاد إلى القصّ الأوسط بلا تغيير سلوك.
 */
export function documentSerialDisplay(
  value?: string | null,
  maxDigits: number = MAX_SERIAL_DIGITS,
): string {
  const text = String(value ?? "").trim();
  if (!text) return "";
  // «بادئة ثمّ فاصل ثمّ تسلسل»: الفاصل إلزامي متى وُجدت بادئة، وإلا صار
  // كل رقم طويل تسلسلاً قصيراً مزعوماً. والبادئة `.*?` لا `\D*?` لأنها قد
  // تحمل سنةً (`PO/2026-0042` ← `42`).
  const match = /^(?:(.*?)[\s\-_/\\])?0*(\d+)$/.exec(text);
  const serial = match?.[2];
  if (serial && serial.length <= maxDigits) return serial;
  return elideDocumentNumber(text);
}
